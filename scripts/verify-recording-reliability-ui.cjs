/* global window, document */
const assert = require('node:assert/strict')
const { start } = require('./test-support/recording-ui-harness.cjs')

;(async () => {
  const h = await start(), p = h.page
  const emit = (channel, id, text) => p.evaluate(({ channel, id, text }) => {
    window.__audit.channels[channel].dispatchEvent(new MessageEvent('message', { data: JSON.stringify({ type: 'conversation.item.input_audio_transcription.completed', item_id: id, transcript: text }) }))
  }, { channel, id, text })
  try {
    // Local recording must work before credentials or a provider connection exist.
    await h.openMode('Meeting transcription')
    await p.evaluate(() => { window.__audit.delayInput = true })
    await p.getByRole('button', { name: 'Start', exact: true }).click()
    await p.waitForFunction(() => window.__audit.releaseInput)
    await p.getByRole('button', { name: 'Stop', exact: true }).click()
    await p.evaluate(() => { window.__audit.delayInput = false; window.__audit.releaseInput() })
    await p.waitForTimeout(250)
    assert.equal(await p.evaluate(() => window.__audit.calls.includes('meetingTranscription.backupStart')), false)
    await p.getByRole('button', { name: 'Start', exact: true }).click()
    await p.waitForFunction(() => window.__audit.calls.includes('meetingTranscription.backupStart'))
    assert.equal(await p.evaluate(() => window.__audit.calls.includes('realtime.createTranscriptionAnswer')), false)
    await p.getByRole('button', { name: 'Stop', exact: true }).click()
    await p.waitForFunction(() => window.__audit.calls.includes('meetingTranscription.backupStop'))

    await h.openMode('Live assistant')
    await p.getByRole('button', { name: 'Start listening', exact: true }).click()
    await p.locator('input[type=password]').first().fill('synthetic-key')
    await p.getByRole('button', { name: 'Save', exact: true }).click()
    await h.openMode('Live assistant')
    await p.evaluate(() => { window.__audit.failRealtime = true })
    const stopsBeforeFailure = await p.evaluate(() => window.__audit.calls.filter(c => c === 'meetingTranscription.backupStop').length)
    await p.getByRole('button', { name: 'Start listening', exact: true }).click()
    await p.waitForFunction(() => document.body.innerText.includes('Synthetic STT unavailable'))
    assert.equal(await p.getByRole('button', { name: 'Start listening', exact: true }).count(), 0)
    assert.equal(await p.evaluate(() => window.__audit.calls.filter(c => c === 'meetingTranscription.backupStop').length), stopsBeforeFailure)
    await p.getByRole('button', { name: 'Stop listening', exact: true }).click()
    await p.evaluate(() => { window.__audit.failRealtime = false; window.__audit.channels = []; window.__audit.tracks = [] })
    await h.openMode('Settings')
    await p.getByRole('tab', { name: 'Звук', exact: true }).click()
    await p.getByLabel('Settings other side input', {exact:true}).selectOption('synthetic-loopback')
    await h.openMode('Live assistant')
    await p.getByRole('button', { name: 'Start listening', exact: true }).click()
    await p.waitForFunction(() => window.__audit.channels?.length === 2)
    assert.deepEqual(await p.evaluate(() => window.__audit.realtimeRequests.slice(-2).map(request=>request.latencyMode)), ['conversation', undefined])
    assert.deepEqual(await p.evaluate(() => window.__audit.tracks), ['synthetic-loopback', 'mic'])
    await emit(1, 'me', 'My own answer must only be recorded, not analyzed.')
    await p.waitForTimeout(1400)
    assert.equal(await p.evaluate(() => window.__audit.requests.length), 0)
    await emit(0, 'other', 'Could you explain how you manage a difficult project?')
    await p.waitForFunction(() => window.__audit.requests.length > 0)
    await p.waitForFunction(() => document.querySelector('.call-answer > p')?.textContent.startsWith('I would'))
    assert.equal(await p.evaluate(() => window.__audit.current.segments.find(s => s.sourceItemId === 'microphone:me')?.speaker), 'ME')
    assert.equal(await p.evaluate(() => window.__audit.current.segments.find(s => s.sourceItemId === 'system:other')?.source), 'system')

    await p.evaluate(() => { window.__audit.api.assistant.analyzeRecentTranscript = () => new Promise(resolve => { window.__audit.resolveOld = () => resolve({ ok: true, data: { meaningRu: 'old', suggestedAnswers: [{ text: 'OBSOLETE ANSWER' }], keywordsToRemember: [] } }) }) })
    await emit(0, 'delayed', 'Could you describe your experience managing teams?')
    await p.waitForFunction(() => window.__audit.resolveOld, {}, { timeout: 20000 })
    await p.getByRole('button', { name: 'Stop listening', exact: true }).click()
    await p.getByLabel('Conversation options', {exact:true}).click()
    await p.getByRole('button', { name: 'Show conversation details' }).click()
    await p.getByRole('button', { name: 'Reset conversation', exact: true }).click()
    await p.evaluate(() => window.__audit.resolveOld())
    await p.waitForTimeout(1500)
    assert.equal((await p.locator('body').innerText()).includes('OBSOLETE ANSWER'), false)
    assert.deepEqual(h.errors, [])
    assert.deepEqual(h.blocked, [])
    await h.snap('stopped-no-stale-answer')
    console.log('PASS: offline local recording; system OTHER + microphone ME; Stop/Reset rejects delayed answer; no external requests')
  } finally { await h.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
